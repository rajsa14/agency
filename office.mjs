#!/usr/bin/env node
// The agency office, run locally.
//   node office.mjs              open the office at http://localhost:5190
//   node office.mjs build        regenerate server/seed.js from agents/*.md (the staff a new database starts with)
//   node office.mjs sync         install agents/*.md and the run-agency skill into ~/.claude
//   node office.mjs queue        list the tasks
//   node office.mjs next         hand the next ready task to Claude Code (nothing is handed out 22:00-06:00)
//   node office.mjs done <id>    finish it; the result is read from work/results/<id>.md
//   node office.mjs fail <id> <reason>
//
// The same backend (server/app.js) runs on Cloudflare through worker.js. Here it gets a SQLite file in work/
// and no login unless ADMIN_PASSWORD is set, because the server only listens on this computer.
import { createServer } from 'node:http'
import { Readable } from 'node:stream'
import { readFileSync, writeFileSync, readdirSync, copyFileSync, mkdirSync, existsSync } from 'node:fs'
import { join, dirname, extname, normalize, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { homedir } from 'node:os'

const ROOT = dirname(fileURLToPath(import.meta.url))
const AGENTS = join(ROOT, 'agents')
const PUBLIC = join(ROOT, 'public')
const WORK = join(ROOT, 'work')
const RESULTS = join(WORK, 'results')
const SKILL = join(ROOT, '.claude', 'skills', 'run-agency', 'SKILL.md')
const HOME = join(homedir(), '.claude')
const PORT = 5190

const HAIR = ['spikes', 'tuft', 'parting', 'curl', 'bald']
const PROPS = ['clipboard', 'hardhat', 'pencil', 'check', 'magnifier', 'envelope', 'megaphone', 'none']

// ---------- agent files ----------
const split = (raw) => raw.replace(/\r\n/g, '\n').match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/)

function unquote(v) {
  if (/^".*"$/.test(v)) {
    try { return JSON.parse(v) } catch { return v.slice(1, -1) }
  }
  return /^'.*'$/.test(v) ? v.slice(1, -1) : v
}

const quote = (v) => (/^[\p{L}\p{N}][\p{L}\p{N} .,()/&+-]*$/u.test(v) ? v : JSON.stringify(v))

const files = () => readdirSync(AGENTS).filter((f) => /^[a-z0-9-]+\.md$/.test(f)).sort()

function read(file) {
  const m = split(readFileSync(join(AGENTS, file), 'utf8'))
  if (!m) return null
  const meta = {}
  for (const line of m[1].split('\n')) {
    const i = line.indexOf(':')
    if (i > 0) meta[line.slice(0, i).trim()] = unquote(line.slice(i + 1).trim())
  }
  const tools = meta.tools || ''
  return {
    id: file.replace(/\.md$/, ''),
    name: meta.name || file,
    role: meta.job || meta.name || file,
    department: meta.department || 'Unassigned',
    floor: Number(meta.floor) || 0,
    sort: Number(meta.desk) || 99,
    description: meta.description || '',
    instructions: m[2].trim(),
    // An agent with no tool list has every tool in Claude Code; in the web office the only real tool is web search.
    web_search: !tools || /WebSearch/.test(tools) ? 1 : 0,
    is_manager: meta.avatar === 'claude' ? 1 : 0,
    color: /^#[0-9a-f]{6}$/i.test(meta.color || '') ? meta.color : '#4f6bff',
    look: {
      avatar: meta.avatar === 'claude' ? 'claude' : 'helper',
      eyes: meta.avatar_eyes === '1' ? 1 : 2,
      hair: HAIR.includes(meta.avatar_hair) ? meta.avatar_hair : 'tuft',
      prop: PROPS.includes(meta.avatar_prop) ? meta.avatar_prop : 'none',
    },
  }
}

function build() {
  const seed = files().map(read).filter(Boolean)
  writeFileSync(join(ROOT, 'server', 'seed.js'), `// Generated by \`node office.mjs build\` from agents/*.md. A new database starts with this staff.\nexport const SEED = ${JSON.stringify(seed, null, 1)}\n`)
  return seed
}

function sync(only) {
  mkdirSync(join(HOME, 'agents'), { recursive: true })
  const list = only ? [only] : files()
  for (const f of list) copyFileSync(join(AGENTS, f), join(HOME, 'agents', f))
  if (!only) {
    mkdirSync(join(HOME, 'skills', 'run-agency'), { recursive: true })
    copyFileSync(SKILL, join(HOME, 'skills', 'run-agency', 'SKILL.md'))
  }
  return list
}

// When an agent that came from agents/*.md is edited in the office, its file follows, so Claude Code keeps the same staff.
function agentSaved(agent) {
  const file = `${agent.id}.md`
  if (!existsSync(join(AGENTS, file))) return
  const m = split(readFileSync(join(AGENTS, file), 'utf8'))
  const lines = m[1].split('\n')
  const set = { job: agent.role, department: agent.department, description: agent.description.replace(/\s+/g, ' ') || agent.role, avatar_eyes: String(agent.look.eyes), avatar_hair: agent.look.hair, avatar_prop: agent.look.prop }
  for (const [key, value] of Object.entries(set)) {
    const line = `${key}: ${quote(value)}`
    const at = lines.findIndex((l) => l.startsWith(`${key}:`))
    if (at >= 0) lines[at] = line
    else lines.push(line)
  }
  writeFileSync(join(AGENTS, file), `---\n${lines.join('\n')}\n---\n\n${agent.instructions.trim()}\n`)
  sync(file)
  build()
}

// ---------- database and server ----------
async function open() {
  try {
    process.loadEnvFile(join(ROOT, '.env'))
  } catch {}
  const { DatabaseSync } = await import('node:sqlite')
  const { sqlite } = await import('./server/db.js')
  mkdirSync(RESULTS, { recursive: true })
  const database = new DatabaseSync(join(WORK, 'agency.db'))
  database.exec('PRAGMA journal_mode = WAL')
  return sqlite(database)
}

const TYPES = { '.html': 'text/html', '.css': 'text/css', '.js': 'text/javascript', '.svg': 'image/svg+xml', '.png': 'image/png', '.json': 'application/json', '.ico': 'image/x-icon' }

async function serve() {
  const db = await open()
  const { createApp } = await import('./server/app.js')
  const app = createApp({ db, env: { ...process.env, LOCAL: '1' }, hooks: { agentSaved } })
  const hosts = [`localhost:${PORT}`, `127.0.0.1:${PORT}`]

  createServer(async (req, res) => {
    try {
      // The server changes files and spends API credit, so it answers only to this machine's own page.
      if (!hosts.includes(req.headers.host)) return res.writeHead(403).end('forbidden')
      const url = new URL(req.url, `http://${req.headers.host}`)

      if (url.pathname.startsWith('/api/')) {
        const headers = Object.fromEntries(Object.entries(req.headers).filter(([, v]) => typeof v === 'string'))
        const init = { method: req.method, headers }
        if (!['GET', 'HEAD'].includes(req.method)) Object.assign(init, { body: Readable.toWeb(req), duplex: 'half' })
        const response = await app.fetch(new Request(url, init))
        res.writeHead(response.status, Object.fromEntries(response.headers))
        if (response.body) for await (const chunk of response.body) res.write(chunk)
        return res.end()
      }

      const wanted = normalize(join(PUBLIC, url.pathname === '/' ? 'index.html' : decodeURIComponent(url.pathname)))
      if (!wanted.startsWith(PUBLIC + sep) || !existsSync(wanted)) return res.writeHead(404).end('not found')
      res.writeHead(200, { 'Content-Type': `${TYPES[extname(wanted)] || 'application/octet-stream'}; charset=utf-8`, 'Cache-Control': 'no-store' })
      res.end(readFileSync(wanted))
    } catch (e) {
      console.error(e)
      if (!res.headersSent) res.writeHead(500)
      res.end()
    }
  }).listen(PORT, '127.0.0.1', () => {
    console.log(`Agency office open at http://localhost:${PORT}`)
    console.log(process.env.ANTHROPIC_API_KEY ? 'AI: Anthropic API key found.' : 'AI: no ANTHROPIC_API_KEY set. Put it in .env to run tasks, or switch on dev mode in Settings.')
  })
}

const [command, id, ...rest] = process.argv.slice(2)
try {
  if (command === 'build') console.log(`server/seed.js: ${build().length} agents`)
  else if (command === 'sync') console.log(`Installed into ${HOME}:\n  ${sync().join('\n  ')}\n  skills/run-agency`)
  else if (['queue', 'next', 'done', 'fail'].includes(command)) {
    const db = await open()
    const api = await import('./server/app.js')
    const { ready } = await import('./server/db.js')
    await ready(db)
    if (command === 'queue') console.log(JSON.stringify(await db.all(`SELECT id, title, agent_id, status, priority FROM tasks WHERE kind = 'task' ORDER BY created_at`), null, 1))
    if (command === 'next') {
      const task = await api.claimNext(db)
      console.log(JSON.stringify(task.id ? { ...task, result: join(RESULTS, `${task.id}.md`), files: join(WORK, 'files') } : task, null, 1))
    }
    if (command === 'done') {
      const path = join(RESULTS, `${id}.md`)
      if (!existsSync(path)) throw new Error(`write the result to ${path} first`)
      await api.finishExternal(db, id, readFileSync(path, 'utf8'))
      console.log(`done ${id} - waiting for approval in the office`)
    }
    if (command === 'fail') {
      await api.finishExternal(db, id, '', rest.join(' ').slice(0, 500) || 'failed')
      console.log(`failed ${id}`)
    }
  } else await serve()
} catch (e) {
  console.error(e.message)
  process.exit(1)
}
